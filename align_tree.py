        if not os.path.exists(path):
            with open(path, 'w') as file:
                # Add minimal valid implementation if it's a python file to avoid "ghost files"
                if f.endswith('.py'):
                    class_name = ''.join(word.title() for word in f.replace('.py', '').split('_') if word.isalpha())
                    file.write(f'# {f}\\n\\nclass {class_name if class_name else "Impl"}:\\n    def execute(self):\\n        return True\\n')
                elif f.endswith('.yaml') or f.endswith('.yml'):
                    file.write(f'# {f}\\nkey: value\\n')
                else:
                    file.write(f'# {f}\\n')

